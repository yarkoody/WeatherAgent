"""Sensitivity of the expected-days ranking to the stated assumptions (formula v2).

    python -m app.sensitivity        # writes evals/results/sensitivity.md

Typical-year (expected days) ranking: each days-per-event value halved and doubled one at a time, the NRI /
observed blend from 0.3 to 1.0, and the large-county reference area at 500 and 2,000 sq mi.
Bad-year (TVaR95) ranking: the hurricane closure mix at 70/30 and 90/10, and the long closure at 20 and 50 days.
For each variant: Spearman rank correlation with the current ranking (on unrounded values), the top hub, and the
hub whose rank moved most. Deterministic: same snapshot, same report.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from app import scoring
from app.schemas import Hub

OUT = Path(__file__).resolve().parent.parent / "evals" / "results" / "sensitivity.md"
BLENDS = (0.3, 0.4, 0.5, 0.6, 0.7, 0.8, 0.9, 1.0)
AREAS = (500.0, 2000.0)
LABELS = {"HRCN": "hurricane", "ISTM": "ice storm", "IFLD": "inland flood", "CFLD": "coastal flood",
          "WNTW": "winter weather", "CWAV": "cold wave", "TRND": "tornado", "SWND": "strong wind", "HAIL": "hail"}


@dataclass(frozen=True)
class Row:
    group: str
    label: str
    spearman: float
    top_hub: str
    top_changed: bool
    biggest_move: str  # "hub +n" (moved up n places) / "hub -n", or "none"


@dataclass(frozen=True)
class Result:
    base_order: list[str]
    rows: list[Row]
    data_as_of: str
    base_bad_year_order: list[str]


def spearman(a: list[str], b: list[str]) -> float:
    """Spearman rank correlation of two orderings of the same items (no ties: ties already broken by id)."""
    n = len(a)
    if n < 2:
        return 1.0
    rb = {k: i for i, k in enumerate(b)}
    d2 = sum((i - rb[k]) ** 2 for i, k in enumerate(a))
    return round(1 - 6 * d2 / (n * (n * n - 1)), 3)


def _sorted(values: dict[str, float]) -> list[str]:
    return sorted(values, key=lambda k: (-values[k], k))


def expected_order(hubs: list[Hub], snapshot: scoring.Snapshot, config: scoring.ScoringConfig) -> list[str]:
    return _sorted({h.id: scoring.expected_days(h, snapshot, config) for h in hubs})


def bad_year_order(hubs: list[Hub], snapshot: scoring.Snapshot, config: scoring.ScoringConfig) -> list[str]:
    return _sorted({h.id: scoring.bad_year_days(h, snapshot, config) for h in hubs})


def _row(group: str, label: str, base: list[str], order: list[str]) -> Row:
    pos = {k: i for i, k in enumerate(base)}
    moves = sorted(((pos[k] - i, k) for i, k in enumerate(order)), key=lambda m: (-abs(m[0]), m[1]))
    delta, hub = moves[0]
    move = "none" if delta == 0 else f"{hub} {delta:+d}"
    return Row(group, label, spearman(base, order), order[0], order[0] != base[0], move)


def run(hubs: list[Hub], snapshot: scoring.Snapshot, config: scoring.ScoringConfig = scoring.DEFAULT_CONFIG) -> Result:
    base = expected_order(hubs, snapshot, config)
    rows = []
    for key in config.days_per_event:
        for factor in (0.5, 2):
            dpe = {**config.days_per_event, key: config.days_per_event[key] * factor}
            cfg = config.model_copy(update={"days_per_event": dpe})
            rows.append(_row("days per event", f"{key} x{factor:g}", base, expected_order(hubs, snapshot, cfg)))
    for w in BLENDS:
        cfg = config.model_copy(update={"nri_weight": w, "observed_weight": round(1 - w, 10)})
        rows.append(_row("NRI / observed blend", f"NRI {w:.1f} / observed {1 - w:.1f}", base,
                         expected_order(hubs, snapshot, cfg)))
    for area in AREAS:
        cfg = config.model_copy(update={"reference_area_sq_mi": area})
        rows.append(_row("reference area", f"{area:,.0f} sq mi", base, expected_order(hubs, snapshot, cfg)))
    bad_base = bad_year_order(hubs, snapshot, config)
    (s_short, d_short), (s_long, d_long) = config.hurricane_days_mix
    for label, mix in (
        ("mix 70% / 30%", ((0.7, d_short), (0.3, d_long))),
        ("mix 90% / 10%", ((0.9, d_short), (0.1, d_long))),
        ("long closure 20 days", ((s_short, d_short), (s_long, 20.0))),
        ("long closure 50 days", ((s_short, d_short), (s_long, 50.0))),
    ):
        cfg = config.model_copy(update={"hurricane_days_mix": mix})
        rows.append(_row("bad-year: hurricane closures", label, bad_base, bad_year_order(hubs, snapshot, cfg)))
    return Result(base, rows, snapshot.data_as_of, bad_base)


def to_markdown(result: Result) -> str:
    lines = [
        "# Sensitivity of the hub rankings",
        "",
        f"Snapshot {result.data_as_of}. Generated by `python -m app.sensitivity`; deterministic.",
        "",
        f"Current typical-year ranking (expected disruption days per year): {', '.join(result.base_order)}.",
        "",
        f"Current bad-year ranking (average lost days in the worst 1 in 20 years): "
        f"{', '.join(result.base_bad_year_order)}.",
        "",
        "Each row changes one assumption and compares the new ranking of all hubs with the current one, on unrounded",
        "values. The first three groups test the typical-year ranking; the last tests the bad-year ranking.",
        "Spearman 1.0 = identical order. Biggest move: the hub whose rank changed most (+ = moved up).",
        "",
    ]
    for group in ("days per event", "NRI / observed blend", "reference area", "bad-year: hurricane closures"):
        rows = [r for r in result.rows if r.group == group]
        lines += [f"## {group[0].upper() + group[1:]}", "", "| Variant | Spearman | Top hub | Top changed | Biggest move |",
                  "|---|---|---|---|---|"]
        for r in rows:
            label = r.label
            if group == "days per event":
                key, factor = r.label.split(" ")
                label = f"{r.label} ({LABELS[key]} {factor.replace('x', '×')})"
            lines.append(f"| {label} | {r.spearman:.3f} | {r.top_hub} | {'yes' if r.top_changed else 'no'} | {r.biggest_move} |")
        lowest = min(rows, key=lambda r: (r.spearman, r.label))
        changed = [r.label for r in rows if r.top_changed]
        lines += ["", f"Lowest Spearman: {lowest.spearman:.3f} ({lowest.label}). "
                  + (f"Top hub changes under: {', '.join(changed)}." if changed else "The top hub never changes."), ""]
    return "\n".join(lines)


def main() -> None:
    result = run(scoring.load_hubs(), scoring.load_snapshot())
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(to_markdown(result))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
